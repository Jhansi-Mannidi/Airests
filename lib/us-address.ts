const ZIP_PATTERN = /^\d{5}(?:-\d{4})?$/

export function formatUsAddress(address: UsAddress) {
  const line1 = [address.street.trim(), address.apt.trim()].filter(Boolean).join(', ')
  const cityState = [address.city.trim(), address.state.trim()].filter(Boolean).join(', ')
  const line2 = [cityState, address.zip.trim()].filter(Boolean).join(' ')
  return [line1, line2].filter(Boolean).join(', ')
}

export function usAddressError(address: UsAddress) {
  if (!address.street.trim()) return 'Enter a street address'
  if (!address.city.trim()) return 'Enter a city'
  if (!address.state.trim()) return 'Select a state'
  if (!ZIP_PATTERN.test(address.zip.trim())) return 'Enter a 5-digit ZIP code'
  return null
}
